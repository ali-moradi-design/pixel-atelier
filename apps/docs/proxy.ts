import { type NextRequest, NextResponse } from "next/server";

// Strict Content Security Policy with a fresh nonce per request, as in the
// Next.js guide "Content Security Policy" (section "Nonces"). Next.js adds the
// nonce to its own scripts; inline scripts without it cannot run.
export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const isDev = process.env.NODE_ENV === "development";
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'", // style attributes (CSS variables); cannot run code
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'", // demo forms never submit anywhere
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", csp);
  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", csp);
  return response;
}

export const config = {
  matcher: [
    {
      // pages only: not the static files, Storybook (own CSP) or the registry JSON
      source:
        "/((?!_next/static|_next/image|storybook|r/|favicon|apple-touch-icon|brand|fonts|.*\\.(?:svg|png|ico|jpg|webp|woff2|json|txt|xml|webmanifest)$).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
